"""Step 5: every number quoted in the manuscript, written as LaTeX macros (results/numbers.tex),
plus result tables. The manuscript must take its numbers from this file only.

Run after 01-02 (data numbers) and again after 03-05 (model results).
"""
from __future__ import annotations

import json

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, roc_auc_score

from common import label_col, load_config, p, variant_name

DIGITS = {"0": "zero", "1": "one", "2": "two", "3": "three", "4": "four", "5": "five",
          "6": "six", "7": "seven", "8": "eight", "9": "nine"}


def macro_name(name: str) -> str:
    """LaTeX macro names cannot contain digits: N5 -> Nfive, b50 -> bfivezero."""
    return "".join(DIGITS.get(c, c) for c in name if c.isalnum())


class Numbers:
    def __init__(self):
        self.items: list[tuple[str, str, str]] = []

    def add(self, name: str, value, fmt: str = "{:,}", note: str = "") -> None:
        if isinstance(value, (float, np.floating)) and fmt == "{:,}":
            fmt = "{:.3f}"
        s = fmt.format(value).replace(",", "{,}")
        self.items.append((macro_name(name), s, note))

    def write(self, path) -> None:
        lines = ["% AUTO-GENERATED by src/07_tables.py -- do not edit by hand.", ""]
        for n, v, note in self.items:
            lines.append(f"\\newcommand{{\\{n}}}{{{v}}}" + (f"  % {note}" if note else ""))
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def data_numbers(cfg: dict, X: Numbers) -> None:
    proc = p(cfg, "processed_dir")
    info = json.load(open(proc / "build_info.json"))
    split = json.load(open(proc / "splits_summary.json"))
    counts = pd.read_csv(proc / "gbif_filter_counts.csv")
    d = pd.read_parquet(proc / "plots.parquet")
    B = cfg["spatial"]["buffer_km"]
    V = variant_name(cfg["gbif"]["missing_uncertainty"], cfg["gbif"]["basis_of_record_main"])
    Vall = variant_name(cfg["gbif"]["missing_uncertainty"], "all")
    e = d[d["eligible_N5"]]

    X.add("nPlotsTotal", info["splot"]["n_header"], note="sPlotOpen plots")
    X.add("nPlotsNoDate", info["splot"]["n_no_survey_year"])
    X.add("surveyYearMin", info["splot"]["survey_year_min"], "{}")
    X.add("surveyYearMax", info["splot"]["survey_year_max"], "{}")
    sy = d["survey_year"]
    X.add("pctPlotsPreNineteen", 100 * float((sy < cfg["gbif"]["year_min"] - 1).sum() / sy.notna().sum()),
          "{:.0f}", "dated plots surveyed before 1999 (%)")
    X.add("nEligible", len(e))
    X.add("nEligibleCoords", int(e[["Latitude", "Longitude"]].drop_duplicates().shape[0]))
    X.add("nEligibleDatasets", int(e["Dataset"].nunique()))

    X.add("gbifRecordsRaw", info["gbif_raw_records"])
    X.add("gbifSpecies", info["gbif_raw_species"])
    tot = counts[counts["species"] == "TOTAL"].set_index("variant")
    t = tot.loc[V]
    X.add("gbifPresent", int(t["2_status_present"]))
    unc_col = [c for c in t.index if c.startswith("5_") and pd.notna(t[c])][0]
    X.add("gbifUncOK", int(t[unc_col]))
    bor_col = [c for c in t.index if c.startswith("6_") and pd.notna(t[c])][0]
    X.add("gbifNoMS", int(t[bor_col]))
    X.add("gbifFinal", int(t["7_dedup_species_coord0.01_year"]), note="main variant after dedup")
    X.add("gbifFinalAllBasis", int(tot.loc[Vall, "7_dedup_species_coord0.01_year"]))
    X.add("gbifFinalUncDrop", int(tot.loc[variant_name("drop", cfg["gbif"]["basis_of_record_main"]),
                                          "7_dedup_species_coord0.01_year"]))
    raw = pd.read_csv(p(cfg, "gbif_download"), sep="\t", quoting=3, dtype=str,
                      keep_default_na=False, na_values=[""])
    X.add("pctUncMissing", 100 * raw["coordinateUncertaintyInMeters"].isna().mean(), "{:.0f}")
    X.add("pctMaterialSample", 100 * (raw["basisOfRecord"] == "MATERIAL_SAMPLE").mean(), "{:.0f}")
    X.add("nMaterialSample", int((raw["basisOfRecord"] == "MATERIAL_SAMPLE").sum()))

    for N in cfg["labels"]["horizons"]:
        y = e[label_col(N, B, V)]
        X.add(f"prevN{N}", 100 * y.mean(), "{:.1f}", f"% positive, main, N={N}")
        X.add(f"nPosN{N}", int(y.sum()))
        X.add(f"prevAllBasisN{N}", 100 * e[label_col(N, B, Vall)].mean(), "{:.1f}")
    pr = e[f"prior_any_b{B}_{V}"]
    X.add("pctPrior", 100 * pr.mean(), "{:.1f}")
    for N in cfg["labels"]["horizons"]:
        y = e[label_col(N, B, V)]
        X.add(f"prevGivenPriorN{N}", 100 * y[pr == 1].mean(), "{:.0f}")
        X.add(f"prevGivenNoPriorN{N}", 100 * y[pr == 0].mean(), "{:.1f}")
        s = e[f"n_outwin_N{N}_b{B}_{V}"]
        X.add(f"effortOutROCN{N}", roc_auc_score(y, s), "{:.2f}", "effort outside label window")
        X.add(f"effortOutPRN{N}", average_precision_score(y, s), "{:.2f}")
        s = e[f"n_prior_b{B}_{V}"]
        X.add(f"priorCountPRN{N}", average_precision_score(y, s), "{:.2f}", "prior count as score")
        X.add(f"priorCountROCN{N}", roc_auc_score(y, s), "{:.2f}")
    for c, nm in [("Europe", "Europe"), ("North America", "NorthAmerica"), ("Oceania", "Oceania")]:
        X.add(f"prevContN10{nm}", 100 * e.loc[e["Continent"] == c, label_col(10, B, V)].mean(), "{:.1f}")

    X.add("nBlocks", split["n_blocks"])
    X.add("blockKm", split["block_km"])
    ns = [v["n"] for v in split["spatial_folds"].values()]
    X.add("foldSizeMin", min(ns))
    X.add("foldSizeMax", max(ns))
    X.add("nFolds", cfg["evaluation"]["n_folds"])
    X.add("nSeeds", len(cfg["seeds"]))
    X.add("nTrials", cfg["tabular"]["n_trials"])
    X.add("tuningHorizon", cfg["evaluation"]["tuning_horizon"])
    X.add("bufferKm", B)
    X.add("kNeighbours", cfg["graph"]["k"])


def main() -> None:
    cfg = load_config()
    X = Numbers()
    data_numbers(cfg, X)
    out = p(cfg, "results_dir")
    out.mkdir(exist_ok=True)
    X.write(out / "numbers.tex")
    print(f"wrote {len(X.items)} macros to {out / 'numbers.tex'}")
    print("\n".join(f"\\{n} = {v}" for n, v, _ in X.items))


if __name__ == "__main__":
    main()
